// Task 11 C6:出站 Markdown 检测契约(冻结,spec C6)——强信号单命中走卡片,
// 弱信号 ≥2 类共现,转义不计。改这里的期望值 = 改 spec,需评审。
import { describe, it, expect } from "vitest";
import { hasRichMarkdown } from "../server/gateway/md-detect.mjs";

describe("C6 Markdown 检测契约(冻结)", () => {
  it.each([
    ["| 名称 | 状态 |\n|---|---|\n| a | ok |", true, "表格"],
    ["看这段:\n```js\nlet a=1\n```", true, "代码围栏"],
    ["# 本周计划\n先做A", true, "行首标题"],
    ["> 引用原话\n然后说", true, "引用"],
    ["上半段\n---\n下半段", true, "分隔线"],
    ["详见 [文档](https://x.y/z)", true, "链接"],
    ["- 第一项\n- 第二项\n**重点**在后面", true, "弱信号共现(列表+加粗)"],
    // §5.2 审卷补杀:每种弱信号都至少进一个两类共现正例
    ["1. 先做这个\n**重点**别忘了", true, "弱信号共现(有序列表+加粗)"],
    ["先跑 `npm test`\n- 然后看结果", true, "弱信号共现(行内代码+无序列表)"],
  ])("强/共现信号走卡片: %s", (text, want) => expect(hasRichMarkdown(text)).toBe(want));

  it.each([
    ["#话题 今天聊聊这个", "无空格井号"],
    ["方案A|方案B 二选一", "句中单竖线"],
    ["这里有个星号*但只有一个", "单星号"],
    ["就一句普通话,啥标记都没有", "长纯文本"],
    ["- 只有一个列表信号", "弱信号单发"],
    ["转义\\*\\*不算加粗\\*\\*,列表也\\- 不算", "转义不计"],
    ["\\## 这不是标题", "转义剥离不得造出行首标题(§5.1 审核反例)"],
    ["\\> 这不是引用", "转义剥离不得造出引用"],
    // §5.2 审卷补杀:整段转义预处理被删即红——转义链接不算强信号
    ["详见 \\[文档](https://x.y/z) 原样发", "转义链接不计"],
    // §5.2 审卷补杀:每个信号的最近邻非法值
    ["| a | b |", "单行竖线无分隔行不是表格"],
    ["| a | b |\n|   |   |", "分隔行无连字符不是表格(实现修正)"],
    ["####### 七个井号不是标题", "标题最多 6 级"],
    [">没空格不算引用", "引用需 > 后空格"],
    ["上半段\n--\n下半段", "两个连字符不是分隔线"],
    ["看 [文本](https://x.y/带 空格) 呢", "URL 含空格不是链接"],
    ["行中 ```不是围栏``` 啦", "围栏必须行首"],
    ["-无空格\n**加粗**", "列表标记后必须空格"],
    ["1.无空格\n**加粗**", "有序列表点后必须空格"],
    // §5.2 审卷补杀:"≥2 类"按类计数,同类重复/混用标记不达阈
    ["- 甲\n* 乙", "混用无序标记仍是同一类"],
    ["- 甲\n- 乙\n- 丙", "同类重复不算共现"],
    ["1. 只有有序列表", "弱信号单发·有序"],
    ["`只有行内代码`", "弱信号单发·行内代码"],
  ])("反例不误判: %s (%s)", (text) => expect(hasRichMarkdown(text)).toBe(false));

  it("空/undefined 安全返回 false", () => {
    expect(hasRichMarkdown("")).toBe(false);
    expect(hasRichMarkdown(undefined)).toBe(false);
    expect(hasRichMarkdown(null)).toBe(false);
  });
});
