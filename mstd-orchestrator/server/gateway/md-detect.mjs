// 出站 Markdown 检测(契约冻结,spec C6):强信号单命中走卡片;弱信号需 ≥2 类共现;转义不计信号。
const STRONG = [
  // 表格:表头行+分隔行(§5.2 审卷修正:分隔行每列必须含连字符,"|   |   |"不是分隔行)
  /^\s*\|.+\|\s*\n\s*\|(?:\s*:?-+:?\s*\|)+\s*$/m,
  /^```/m,                                // 代码围栏
  /^\s*#{1,6}\s+\S/m,                     // 行首标题(# 后必须空格)
  /^\s*>\s+\S/m,                          // 引用
  /^\s*(-{3,}|\*{3,})\s*$/m,              // 独行分隔线
  /\[[^\]]+\]\([^)\s]+\)/,                // [文本](url) 链接
];
const WEAK = [
  /^\s*[-*]\s+\S/m,                       // 无序列表
  /^\s*\d+\.\s+\S/m,                      // 有序列表
  /\*\*[^*\n]+\*\*/,                      // 加粗
  /`[^`\n]+`/,                            // 行内代码
];

export function hasRichMarkdown(text) {
  // §5.1 审核修正:转义序列以非空白哨兵占位而非删成空串——删除会把 "\## x" 剥成
  // "# x" 凭空造出行首标题信号;NUL 非 \s,挡住 ^\s* 锚定,合法信号不受影响
  const t = String(text ?? "").replace(/\\[*`#|>[\]_-]/g, "\u0000");
  if (STRONG.some((re) => re.test(t))) return true;
  return WEAK.filter((re) => re.test(t)).length >= 2;
}
